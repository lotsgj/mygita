import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const engineRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = 'js/content-kit.js';
export const CONTENT_KIT_BUNDLE = 'js/content-kit.bundle.js';

const IMPORT = /^import\s+[^;]+?from\s+['"]([^'"]+)['"];\s*$/gm;
const DECLARATION = /^(?:export\s+)?(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;

// Same module flattening as build-player.mjs: dependencies first, imports and export keywords removed.
async function orderedSources(relative, seen = new Set(), ordered = []) {
  if (seen.has(relative)) return ordered;
  seen.add(relative);
  const code = await readFile(path.join(engineRoot, relative), 'utf8');
  for (const [, specifier] of code.matchAll(IMPORT)) {
    await orderedSources(path.posix.join(path.posix.dirname(relative), specifier), seen, ordered);
  }
  ordered.push({ relative, code });
  return ordered;
}

function strip(code) {
  return code
    .replace(/^import\s+[^;]+;\s*$/gm, '')
    .replace(/^export\s+\*\s+from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s+\{[^}]+\}(?:\s+from\s+['"][^'"]+['"])?;?\s*$/gm, '')
    .replace(/^export\s+(?=(const|let|class|function|async\s+function)\b)/gm, '');
}

export async function buildContentKit() {
  const sources = await orderedSources(entry);
  const declared = new Map();
  for (const { relative, code } of sources) {
    for (const [, name] of code.matchAll(DECLARATION)) {
      if (declared.has(name)) throw new Error(`${name} is declared in both ${declared.get(name)} and ${relative}.`);
      declared.set(name, relative);
    }
  }
  const entryCode = sources.at(-1).code;
  const exported = [...entryCode.matchAll(/^export\s+(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)].map((match) => match[1]);
  const sourceBody = sources.map(({ relative, code }) => '// Source: ' + relative + '\n' + strip(code).trim()).join('\n\n');
  const build = createHash('sha256').update(sourceBody).digest('hex').slice(0, 12);
  const body = sourceBody.replace("const KIT_BUILD = 'source';", `const KIT_BUILD = '${build}';`);
  return [
    '/* Generated by scripts/build-content-kit.mjs from js/content-kit.js. Do not edit directly. */',
    '(() => {',
    "'use strict';",
    '',
    body,
    '',
    `globalThis.MyGitaContentKit = Object.freeze({ ${exported.join(', ')} });`,
    '})();',
    ''
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  await writeFile(path.join(engineRoot, CONTENT_KIT_BUNDLE), await buildContentKit());
}
