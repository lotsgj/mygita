import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const engineRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = path.resolve(engineRoot, '..');
const productsRoot = path.join(repositoryRoot, 'products');

function parseTable(text) {
  const lines = String(text).replace(/^\uFEFF/, '').split(/\r?\n/).filter((line) => line.trim());
  const headers = (lines.shift() || '').split('#').map((value) => value.trim());
  return lines.map((line) => Object.fromEntries(line.split('#').map((value, index) => [headers[index], value.trim()])));
}

async function collectText(directory, prefix = '') {
  const result = {};
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) Object.assign(result, await collectText(absolute, relative));
    else if (/\.(?:csv|json|tsv)$/i.test(entry.name)) result[`data/${relative}`] = await readFile(absolute, 'utf8');
  }
  return result;
}

function productAssetUrl(productPath, value) {
  if (!value || /^(?:https?:|blob:|data:)/i.test(value)) return value;
  return `products/${productPath}/${String(value).replace(/^\.\//, '')}`;
}

function resolveBranding(config, productPath) {
  const result = structuredClone(config);
  const branding = result.branding || {};
  for (const field of ['fluteImage', 'socialImage', 'icon192', 'icon512', 'maskableIcon512', 'appleTouchIcon']) {
    if (branding[field]) branding[field] = productAssetUrl(productPath, branding[field]);
  }
  branding.themeStyles = (branding.themeStyles || []).map((value) => productAssetUrl(productPath, value));
  for (const experience of result.experiences || []) {
    if (experience.cardImage) experience.cardImage = productAssetUrl(productPath, experience.cardImage);
  }
  return result;
}

const app = JSON.parse(await readFile(path.join(productsRoot, 'app.json'), 'utf8'));
// Platform branding paths are relative to products/, unlike product branding paths.
for (const field of ['fluteImage', 'socialImage', 'icon192', 'icon512', 'maskableIcon512', 'appleTouchIcon']) {
  if (app.branding?.[field]) app.branding[field] = `products/${app.branding[field].replace(/^\.\//, '')}`;
}
app.branding.themeStyles = (app.branding?.themeStyles || []).map((value) => `products/${value.replace(/^\.\//, '')}`);

const registry = parseTable(await readFile(path.join(productsRoot, 'collection.csv'), 'utf8'))
  .filter((row) => String(row.enabled).toLowerCase() !== 'false')
  .sort((left, right) => (Number(left.order) || 0) - (Number(right.order) || 0));
const localized = {};
for (const language of app.supportedLanguages || ['en']) {
  localized[language] = parseTable(await readFile(path.join(productsRoot, `collection_${language}.csv`), 'utf8'));
}

const products = [];
const productText = {};
const productBases = {};
for (const row of registry) {
  const productRoot = path.join(productsRoot, row.path);
  const config = resolveBranding(JSON.parse(await readFile(path.join(productRoot, 'data/distribution.json'), 'utf8')), row.path);
  const metadata = Object.fromEntries(Object.entries(localized).map(([language, rows]) => {
    const value = rows.find((entry) => entry.product_id === row.product_id) || {};
    return [language, { name: value.name || row.product_id, shortName: value.short_name || value.name || row.product_id, description: value.description || '' }];
  }));
  productText[row.product_id] = await collectText(path.join(productRoot, 'data'));
  products.push({ id: row.product_id, path: row.path, order: Number(row.order) || products.length + 1, metadata, config, productText: productText[row.product_id] });
  productBases[row.product_id] = `products/${row.path}/`;
}

const output = [
  '/* Generated by scripts/build-local-workspace.mjs. Do not edit directly. */',
  "const __MYGITA_REPOSITORY_ROOT__ = new URL('../../', document.currentScript.src);",
  'const __MYGITA_LOCAL_URL__ = (value) => value && !/^(?:https?:|blob:|data:|file:)/i.test(value) ? new URL(value, __MYGITA_REPOSITORY_ROOT__).href : value;',
  `globalThis.__MYGITA_LOCAL_WORKSPACE__ = ${JSON.stringify({ app, products })};`,
  "for (const config of [globalThis.__MYGITA_LOCAL_WORKSPACE__.app, ...globalThis.__MYGITA_LOCAL_WORKSPACE__.products.map((product) => product.config)]) { const branding = config?.branding || {}; for (const field of ['fluteImage', 'socialImage', 'icon192', 'icon512', 'maskableIcon512', 'appleTouchIcon']) branding[field] = __MYGITA_LOCAL_URL__(branding[field]); branding.themeStyles = (branding.themeStyles || []).map(__MYGITA_LOCAL_URL__); for (const experience of config?.experiences || []) experience.cardImage = __MYGITA_LOCAL_URL__(experience.cardImage); }",
  `globalThis.__MYGITA_PRODUCT_TEXT__ = ${JSON.stringify(productText)};`,
  `globalThis.__MYGITA_PRODUCT_BASES__ = Object.fromEntries(Object.entries(${JSON.stringify(productBases)}).map(([id, value]) => [id, __MYGITA_LOCAL_URL__(value)]));`,
  ''
].join('\n');
await writeFile(path.join(engineRoot, 'js/local-workspace.js'), output);
